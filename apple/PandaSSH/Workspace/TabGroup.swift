// =============================================================================
// TabGroup.swift
// =============================================================================
// 文件功能说明：
// 定义「页签分组」数据模型。页签分组把相关的浏览器/终端页签组织在一起，
// 让用户在视觉上更容易区分不同用途的页签（比如把几台服务器归为一组）。
// 分组状态只在当前会话内保持，关闭应用后不会持久化保存。
// =============================================================================

import Foundation
// 导入 Foundation 框架，提供 UUID、String 等基础类型支持

/// 页签分组：将相关页签组织在一起，便于视觉区分和管理。
/// 分组状态仅在当前会话内保持，不持久化。
struct TabGroup: Identifiable, Equatable {
    // ── Identifiable 协议要求提供 id 属性，SwiftUI 的 ForEach / List 用它来
    //    唯一追踪每一行，避免列表刷新时错乱 ──

    // ── Equatable 协议让两个 TabGroup 可以用 == 比较是否相等，
    //    SwiftUI 借此判断视图是否需要重新渲染 ──

    /// 分组唯一标识
    let id: UUID
    // UUID 是通用唯一识别码，保证每个分组都有独一无二的 id，
    // 即使分组名称相同也不会冲突

    /// 分组名称，用户可编辑
    var name: String
    // 用 var 声明，说明名称可以在运行时被用户修改（比如重命名分组）

    /// 组内页签 ID 列表，有序
    var tabIDs: [UUID]
    // 存储属于这个分组的所有页签的 ID，数组是有序的，
    // 顺序决定了页签在界面上的排列顺序

    /// 分组是否为空（无页签）
    var isEmpty: Bool {
        // 这是一个计算属性（没有存储值），每次访问时实时计算
        tabIDs.isEmpty
        // 调用数组的 isEmpty 属性：如果 tabIDs 里没有任何元素就返回 true，
        // 表示分组为空；否则返回 false
    }
}
